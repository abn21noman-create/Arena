async function main() {
  console.log("🌱 Chemistry 1st+2nd Paper Topic Notes+Formula Sheet Seeding শুরু হচ্ছে...\n");

  let totalUpdated = 0;
  const topicsNotFound: string[] = [];

  for (const [topicName, content] of Object.entries(contentByTopic)) {
    const topic = await prisma.topic.findFirst({
      where: { name: topicName },
    });

    if (!topic) {
      topicsNotFound.push(topicName);
      continue;
    }

    await prisma.topic.update({
      where: { id: topic.id },
      data: {
        notesMarkdown: content.notesMarkdown,
        formulaSheet: content.formulaSheet,
      },
    });

    console.log(`✅ ${topicName} — নোট (${content.notesMarkdown.length} অক্ষর) ও ফর্মুলা শীট যোগ হলো`);
    totalUpdated += 1;
  }

  if (topicsNotFound.length > 0) {
    console.log(`\n⚠️  এই টপিকগুলো পাওয়া যায়নি: ${topicsNotFound.join(", ")}`);
  }

  console.log(`\n✅ মোট ${totalUpdated}টা টপিকে নোট+ফর্মুলা শীট সিড করা হলো!`);
}

main()
