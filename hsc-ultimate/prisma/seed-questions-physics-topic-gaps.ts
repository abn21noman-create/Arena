async function main() {
  console.log("🔍 পদার্থবিজ্ঞানের MCQ-শূন্য টপিকে প্রশ্ন যোগ করা হচ্ছে...\n");

  // দুই পত্রের subject id আলাদা করে নেওয়া — একই code='PHYSICS' শেয়ার করে
  const subjects = await prisma.subject.findMany({
    where: { code: "PHYSICS" },
    select: { id: true, name: true, paper: true },
  });
  const byPaper = new Map(subjects.map((s) => [s.paper, s]));

  if (!byPaper.has("FIRST") || !byPaper.has("SECOND")) {
    throw new Error("পদার্থবিজ্ঞানের দুই পত্র পাওয়া যায়নি");
  }

  let added = 0;
  let skipped = 0;
  const notFound: string[] = [];

  for (const entry of seedData) {
    const subject = byPaper.get(entry.paper)!;

    const topic = await prisma.topic.findFirst({
      where: { name: entry.topicName, chapter: { subjectId: subject.id } },
      select: { id: true },
    });

    if (!topic) {
      notFound.push(`${entry.topicName} (${subject.name})`);
      continue;
    }

    // ডুপ্লিকেট এড়াতে বিদ্যমান প্রশ্নের text সংগ্রহ (deleteMany নয়)
    const existing = await prisma.question.findMany({
      where: { topicId: topic.id },
      select: { text: true },
    });
    const existingTexts = new Set(existing.map((q) => q.text));

    const fresh = entry.questions.filter((q) => !existingTexts.has(q.text));
    skipped += entry.questions.length - fresh.length;

    if (fresh.length > 0) {
      await prisma.question.createMany({
        data: fresh.map((q) => ({
          topicId: topic.id,
          type: "MCQ" as const,
          text: q.text,
          options: q.options,
          correctAnswer: q.correctAnswer,
          explanation: q.explanation,
          difficulty: q.difficulty,
        })),
      });
      added += fresh.length;
    }

    console.log(
      `✅ [${entry.paper === "FIRST" ? "১ম" : "২য়"}] ${entry.topicName} — ${fresh.length} টা নতুন` +
        (fresh.length < entry.questions.length
          ? ` (${entry.questions.length - fresh.length} টা আগেই ছিল)`
          : "")
    );
  }

  if (notFound.length > 0) {
    console.log(`\n⚠️  পাওয়া যায়নি: ${notFound.join(", ")}`);
  }

  console.log(`\n📊 ফলাফল: নতুন ${added} · ডুপ্লিকেট বাদ ${skipped}`);

  // ---------- যাচাই: এখনো MCQ-শূন্য টপিক কয়টা ----------
  for (const s of subjects) {
    const topics = await prisma.topic.findMany({
      where: { chapter: { subjectId: s.id } },
      select: { name: true, _count: { select: { questions: true } } },
    });
    const empty = topics.filter((t) => t._count.questions === 0);
    console.log(`   ${s.name}: MCQ-শূন্য টপিক ${empty.length}/${topics.length}`);
    for (const e of empty) console.log(`      • ${e.name}`);
  }

  const totalQ = await prisma.question.count();
  console.log(`\n🎯 DB তে মোট MCQ: ${totalQ}`);
}

main()
  .catch((e) => {
    console.error("❌ সমস্যা হয়েছে:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
