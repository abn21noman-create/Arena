async function main() {
  assertDestructiveSeedAllowed("seed-cq-hmath1.ts");
  console.log("🌱 Higher Math 1st Paper CQ Seeding শুরু হচ্ছে...\n");

  let totalCreated = 0;
  const topicsNotFound: string[] = [];

  for (const cq of cqData) {
    const topic = await prisma.topic.findFirst({
      where: { name: cq.topicName },
    });

    if (!topic) {
      topicsNotFound.push(cq.topicName);
      continue;
    }

    // idempotent রাখার জন্য একই টপিকের পুরনো CQ মুছে নতুন করে বসানো হচ্ছে
    await prisma.cQQuestion.deleteMany({ where: { topicId: topic.id } });

    await prisma.cQQuestion.create({
      data: {
        topicId: topic.id,
        stimulus: cq.stimulus.trim(),
        questionA: cq.questionA,
        questionB: cq.questionB,
        questionC: cq.questionC,
        questionD: cq.questionD,
        modelAnswerA: cq.modelAnswerA,
        modelAnswerB: cq.modelAnswerB,
        modelAnswerC: cq.modelAnswerC,
        modelAnswerD: cq.modelAnswerD,
      },
    });

    console.log(`✅ ${cq.topicName} — CQ যোগ হলো`);
    totalCreated++;
  }

  if (topicsNotFound.length > 0) {
    console.log(`\n⚠️  এই টপিকগুলো পাওয়া যায়নি: ${topicsNotFound.join(", ")}`);
  }

  console.log(`\n✅ মোট ${totalCreated}টি CQ সিড করা হলো!`);
}

main()
  .catch((e) => {
    console.error("❌ সমস্যা হয়েছে:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
